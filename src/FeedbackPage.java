    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
    JFileChooser fileChooser = new JFileChooser();
    fileChooser.setDialogTitle("Select an image");
    fileChooser.setFileFilter(new javax.swing.filechooser.FileNameExtensionFilter("Image files", "jpg", "png", "gif"));

    int result = fileChooser.showOpenDialog(this);

    if (result == JFileChooser.APPROVE_OPTION) {
        File selectedFile = fileChooser.getSelectedFile();

        // Basic validation
        if (!selectedFile.exists() || !selectedFile.isFile()) {
            JOptionPane.showMessageDialog(this, "Invalid file selected.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String imagePath = selectedFile.getAbsolutePath();
        displayImage(imagePath);
    }
                               
    }//GEN-LAST:event_jButton3ActionPerformed

private void displayImage(String imagePath) {
    try {
        ImageIcon imageIcon = new ImageIcon(imagePath);
        Image image = imageIcon.getImage().getScaledInstance(150, 150, Image.SCALE_SMOOTH);
        imageIcon = new ImageIcon(image);
        jLabel2.setIcon(imageIcon);
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error displaying the image: " + e.getMessage());
    }
}

