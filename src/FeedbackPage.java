private int getCustomerIdForUser(int userId) {
    int customerId = -1;  // Default value indicating "not found"
    try (Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/tastyhub", "root", "queen haya")) {
        // Use the passed userId to query for the customerId
        String query = "SELECT customer_id FROM customer WHERE user_id = ?";
        PreparedStatement pst = con.prepareStatement(query);
        pst.setInt(1, userId);  // Set the user_id parameter for the query
        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            customerId = rs.getInt("customer_id");  // Retrieve the customer_id from the result
            System.out.println("Found customerId: " + customerId);  // Debugging output
        } else {
            System.out.println("No customer found for userId: " + userId);  // Debugging output
        }

        rs.close();
        pst.close();
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error fetching customer_id: " + e.getMessage());
    }
    return customerId;  // Return the customer_id (or -1 if not found)
}
    
private void saveFeedbackToDatabase(String feedback) {
    if (customerId == -1) {
        JOptionPane.showMessageDialog(this, "Cannot save feedback: Customer ID is missing.", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    try (Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/tastyhub", "root", "queen haya")) {
        String query = "INSERT INTO feedback (customer_id, message) VALUES (?, ?)";
        PreparedStatement pst = con.prepareStatement(query);
        pst.setInt(1, customerId);
        pst.setString(2, feedback);
        pst.executeUpdate();
        JOptionPane.showMessageDialog(this, "Feedback submitted successfully!");
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error saving feedback: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
    }
}


