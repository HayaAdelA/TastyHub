private void loadAccountInfo() {
    try {
        Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/tastyhub", "root", "queen haya");

        // Query to fetch user info along with the associated employee info
        String query = "SELECT u.username, u.email, u.password, u.phone, e.department " +
                "FROM USER u " +
                "JOIN EMPLOYEE e ON u.user_id = e.user_id " +
                "WHERE u.user_id = ?";  // Use the userId passed to the constructor

        PreparedStatement pst = con.prepareStatement(query);
        pst.setInt(1, userId);  // Use the passed userId
        ResultSet rs = pst.executeQuery();

        // Debugging: Check if data is fetched
        System.out.println("Executing query: " + query);
        if (rs.next()) {
            System.out.println("Fetched Data: " + rs.getString("username") + ", " + rs.getString("email"));
            
            // Fill the fields with the existing data
            txtUserId.setText(String.valueOf(userId));  // Set user_id (read-only)
            txtUsername.setText(rs.getString("username"));
            txtEmail.setText(rs.getString("email"));
            txtPhone.setText(rs.getString("phone"));
            txtPassword.setText(rs.getString("password"));
            txtDepartment.setText(rs.getString("department"));
        } else {
            System.out.println("No data found for user_id: " + userId);
        }

        rs.close();
        pst.close();
        con.close();
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error loading account: " + e.getMessage());
    }
}

    
    
