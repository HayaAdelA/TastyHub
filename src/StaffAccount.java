    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // Retrieve inputs from the text fields
        String username = txtUsername.getText().trim();
        String email = txtEmail.getText().trim();
        String phone = txtPhone.getText().trim();
        String password = txtPassword.getText().trim();
        String department = txtDepartment.getText().trim();  // Update this to reflect the department

    if (username.isEmpty() || email.isEmpty() || phone.isEmpty() || password.isEmpty() || department.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in all fields.");
        return;
    }
    
    if(!department.matches("[a-zA-Z]+")) {
            JOptionPane.showMessageDialog(this, "Department can only contain letters (no numbers or special characters).", 
                "Name Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

    if (!username.matches("^[a-zA-Z0-9_]+$")) {
        JOptionPane.showMessageDialog(this, "Username must only contain letters, numbers, or underscores.", "Invalid Username", JOptionPane.ERROR_MESSAGE);
        return;
    }

    if (!email.matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+$")) {
        JOptionPane.showMessageDialog(this, "Invalid email format.", "Invalid Email", JOptionPane.ERROR_MESSAGE);
        return;
    }

    if (!phone.matches("^\\+9665\\d{8}$")) {
        JOptionPane.showMessageDialog(this, "Phone must follow Saudi format: +9665XXXXXXXX", "Invalid Phone", JOptionPane.ERROR_MESSAGE);
        return;
    }

    if (password.length() < 6) {
        JOptionPane.showMessageDialog(this, "Password must be at least 6 characters.", "Weak Password", JOptionPane.WARNING_MESSAGE);
        return;
    }


        try {
            Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/tastyhub", "root", "queen haya");

            // Update user details in the USER table
            String updateUserQuery = "UPDATE USER SET username = ?, email = ?, password = ?, phone = ? WHERE user_id = ?";
            PreparedStatement pstUser = con.prepareStatement(updateUserQuery);
            pstUser.setString(1, username);
            pstUser.setString(2, email);
            pstUser.setString(3, password);
            pstUser.setString(4, phone);
            pstUser.setInt(5, userId);
            int rowsAffectedUser = pstUser.executeUpdate();

            
            // Update employee details in the EMPLOYEE table
            String updateEmpQuery = "UPDATE EMPLOYEE SET department = ? WHERE user_id = ?";
            PreparedStatement pstEmp = con.prepareStatement(updateEmpQuery);
            pstEmp.setString(1, department);  // This corresponds to the 'department' in EMPLOYEE table
            pstEmp.setInt(2, userId);  // Use the userId passed to the constructor
            int rowsAffectedEmp = pstEmp.executeUpdate();

            // Close resources
            pstUser.close();
            pstEmp.close();
            con.close();

            if (rowsAffectedUser > 0 || rowsAffectedEmp > 0) {
                JOptionPane.showMessageDialog(this, "Account updated successfully!");
                loadAccountInfo();  // Refresh the account info after updating
            } else {
                JOptionPane.showMessageDialog(this, "No changes made.");
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Update failed: " + e.getMessage());
        }
   
    }//GEN-LAST:event_jButton2ActionPerformed

