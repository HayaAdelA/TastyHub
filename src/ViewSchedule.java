    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
    // Get the selected row
    int row = jTable1.getSelectedRow();
    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Please select an employee.");
        return;
    }

    int employeeId = (int) jTable1.getValueAt(row, 0);  // Get employee ID from the selected row
    String employeeName = (String) jTable1.getValueAt(row, 1);  // Get employee Name

    // Prompt user to enter start time, end time, and date
    String startTime = JOptionPane.showInputDialog(this, "Enter start time (HH:mm):");
    String endTime = JOptionPane.showInputDialog(this, "Enter end time (HH:mm):");
    String date = JOptionPane.showInputDialog(this, "Enter date (yyyy-mm-dd):");

    // Validate the inputs
    if (startTime.isEmpty() || endTime.isEmpty() || date.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in all fields.");
        return;
    }
    
    // Validate empty inputs
    if (startTime.isEmpty() || endTime.isEmpty() || date.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in all fields.");
        return;
    }

    // Validate time format (HH:mm)
    if (!startTime.matches("^([01]\\d|2[0-3]):[0-5]\\d$")) {
        JOptionPane.showMessageDialog(this, "Invalid start time format. Please use HH:mm (e.g., 09:30).", "Time Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    if (!endTime.matches("^([01]\\d|2[0-3]):[0-5]\\d$")) {
        JOptionPane.showMessageDialog(this, "Invalid end time format. Please use HH:mm (e.g., 17:45).", "Time Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Validate date format (yyyy-MM-dd)
    if (!date.matches("^\\d{4}-\\d{2}-\\d{2}$")) {
        JOptionPane.showMessageDialog(this, "Invalid date format. Please use yyyy-MM-dd (e.g., 2025-05-01).", "Date Error", JOptionPane.ERROR_MESSAGE);
        return;
    }


    try {
        Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/tastyhub", "root", "queen haya");

        // Insert the schedule data into the database
        String query = "INSERT INTO SCHEDULE (employee_id, start_time, end_time, date) VALUES (?, ?, ?, ?)";
        PreparedStatement pst = con.prepareStatement(query);
        pst.setInt(1, employeeId);
        pst.setString(2, startTime);
        pst.setString(3, endTime);
        pst.setString(4, date);

        pst.executeUpdate();
        JOptionPane.showMessageDialog(this, "Schedule added successfully.");

        // After inserting, reload the table to reflect the changes
        loadSchedule();  // Refresh the table with updated data

        pst.close();
        con.close();
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error saving schedule: " + e.getMessage());
    }

    }//GEN-LAST:event_jButton2ActionPerformed

