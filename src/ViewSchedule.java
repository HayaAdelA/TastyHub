private void loadSchedule() {
    try {
        Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/tastyhub", "root", "queen haya");

        // Query to fetch employee ids and names from the USER and EMPLOYEE tables
        String query = "SELECT e.employee_id, u.first_name, u.last_name, s.start_time, s.end_time, s.date " +
                       "FROM EMPLOYEE e " +
                       "JOIN USER u ON e.user_id = u.user_id " +
                       "LEFT JOIN SCHEDULE s ON e.employee_id = s.employee_id";

        PreparedStatement pst = con.prepareStatement(query);
        ResultSet rs = pst.executeQuery();

        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0); // Clear previous data

        // Populate the table with employee data and their schedules
        while (rs.next()) {
            int employeeId = rs.getInt("employee_id");
            String firstName = rs.getString("first_name");
            String lastName = rs.getString("last_name");
            String startTime = rs.getString("start_time");
            String endTime = rs.getString("end_time");
            String date = rs.getString("date");

            // Add rows with employee ID, name, and their schedule (if any)
            model.addRow(new Object[]{employeeId, firstName + " " + lastName, startTime, endTime, date});
        }

        rs.close();
        pst.close();
        con.close();
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Failed to load schedule: " + e.getMessage());
    }
}

